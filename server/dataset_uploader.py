import os
import sys
from huggingface_hub import HfApi, create_repo
from dotenv import load_dotenv

def upload_dataset_to_hf(file_path: str, dataset_name: str, collection_name: str):
    """
    Uploads a processed dataset to Hugging Face.
    Naming convention: {username}/{dataset_name}-vml-distilled
    """
    if os.path.exists(".env"):
        load_dotenv(".env")
    elif os.path.exists("../.env"):
        load_dotenv("../.env")
    else:
        load_dotenv()
    
    token = os.getenv("HF_TOKEN")
    if not token:
        return {"error": "HF_TOKEN not found in .env"}

    api = HfApi(token=token)
    
    try:
        user_info = api.whoami()
        username = user_info['name']
    except Exception as e:
        return {"error": f"HF Auth failed: {e}"}

    # Prepare Repo
    repo_id = f"{username}/{dataset_name.lower().replace(' ', '-')}-vml-distilled"
    
    try:
        create_repo(repo_id=repo_id, token=token, private=False, exist_ok=True, repo_type="dataset")
    except Exception as e:
        print(f"Repo creation failed: {e}")

    # Generate README.md for the dataset
    readme_content = f"""
---
license: apache-2.0
task_categories:
- text-generation
language:
- en
tags:
- vml-studio
- distilled
- synthetic
---

# {dataset_name} (Distilled)

This dataset was autonomously generated by **VML-Studio** using Black Box Distillation.

## Collection Source
- **Origin Collection**: {collection_name}
- **Format**: Alpaca (Instruction, Input, Output)
- **Engine**: Kimi (Moonshot AI)

## Usage
This dataset is designed for SFT (Supervised Fine-Tuning) of small language models to specialize them in the domain of the source collection.

Generated via [VML-Studio](https://github.com/vishnusureshperumbavoor/Vibe-ML-platform).
"""
    
    # Upload README
    api.upload_file(
        path_or_fileobj=readme_content.encode(),
        path_in_repo="README.md",
        repo_id=repo_id,
        repo_type="dataset",
        commit_message="Add auto-generated README"
    )

    # Upload Data File
    filename = os.path.basename(file_path)
    try:
        api.upload_file(
            path_or_fileobj=file_path,
            path_in_repo="dataset.jsonl",
            repo_id=repo_id,
            repo_type="dataset",
            commit_message=f"Upload distilled dataset: {filename}"
        )
        return {"success": True, "url": f"https://huggingface.co/datasets/{repo_id}"}
    except Exception as e:
        return {"error": f"Upload failed: {e}"}

if __name__ == "__main__":
    if len(sys.argv) < 4:
        print("Usage: python dataset_uploader.py <file_path> <dataset_name> <collection_name>")
    else:
        res = upload_dataset_to_hf(sys.argv[1], sys.argv[2], sys.argv[3])
        print(res)
